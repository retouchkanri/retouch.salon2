-- ニュースPDF添付の元ファイル名を保持する列を追加。
--
-- 背景: これまで pdf_urls（ストレージURL）しか保存しておらず、URLの
-- ファイル名部分は「Google文字以外を _ に置換」する安全化処理で作られる
-- ため、日本語ファイル名は "_______.pdf" のように潰れてしまう。
-- 会員向け詳細ページでは元名が無いため「添付資料（PDF）1, 2, 3…」という
-- 連番表示にフォールバックしていた。
--
-- pdf_urls と同じ並び順の pdf_names（アップロード時の元ファイル名）を
-- 追加し、詳細ページで元のファイル名をそのまま表示できるようにする。
-- 既存データは元名を保持していないため、再アップロードするまでは
-- 従来どおり連番表示にフォールバックする。

alter table public.news
  add column if not exists pdf_names text[] not null default '{}';
