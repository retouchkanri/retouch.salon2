-- =====================================================================
-- 会員コミュニティ: 6つの公開チャンネルを全会員に表示する（2026-10-13）
--
--   みんなの広場・自己紹介・質問・相談・写真・動画・お知らせ・ご意見箱 を、コミュニティを利用できる
--   会員全員（無料会員を含む）のサイドバーに自動で表示する（公開・全会員・自動参加）。
--   2026-09-28 に「非公開（招待制）」へ変えられていた 4つ（自己紹介・質問・相談・写真・動画・ご意見箱）を
--   公開に戻す。投稿できる人（お知らせは運営のみ、ほかは誰でも）は変えない。
--
--   それ以外のチャンネルは、これまでどおりそのチャンネルのメンバーだけに表示される:
--     会員種別のチャンネル → その会員種別の方 / 支援馬のチャンネル → その馬を支援している方 /
--     運営スタッフ → 運営 / どのチャンネルも、運営が手動で追加した方を含み、外した方を含まない。
--
-- 適用: scripts/apply-community-public-channels.mjs。Supabase ダッシュボード → SQL Editor に全文を
--       貼り付けて Run しても同じ（再実行しても安全）。
-- 元に戻す: 管理画面 → コミュニティ → チャンネル → 編集 で「非公開（招待したメンバーのみ）」に戻す。
-- =====================================================================

update public.community_channels c
  set visibility = 'public',
      audience = 'all',
      audience_plan_codes = '{}',
      audience_horse_ids = '{}',
      auto_join = true
where c.kind = 'channel'
  and c.name in ('みんなの広場', '自己紹介', '質問・相談', '写真・動画', 'お知らせ', 'ご意見箱')
  and (c.visibility <> 'public' or c.audience <> 'all' or not c.auto_join);
